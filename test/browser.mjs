// Optional end-to-end test: install Playwright and Chromium, then run node test/browser.mjs.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.BASE_URL||'http://localhost:3210';
const directory=new URL('../artifacts/',import.meta.url);
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[],notices=[],report={};
const watch=page=>{page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());else if(m.type()==='info')notices.push(m.text());});};
const state=async id=>(await fetch(`${base}/api/rooms/${id}`)).json();
const until=async (predicate,ms=45000)=>{const end=Date.now()+ms;while(Date.now()<end){const result=await predicate();if(result)return result;await new Promise(r=>setTimeout(r,50));}throw new Error('Browser test timed out.');};
try {
  const studio=await browser.newContext({viewport:{width:1440,height:1080}}),page=await studio.newPage();watch(page);
  await page.goto(`${base}/?cpu=1`);
  await page.waitForFunction(()=>document.querySelector('#connection')?.textContent==='Live connection');
  const id=(await page.locator('#room-code').textContent()).trim();report.room=id;await page.locator('[data-preset=solstice]').click();
  await page.screenshot({path:new URL('studio-ready.png',directory).pathname,fullPage:true});
  await page.locator('#contribute-button').click();await page.waitForFunction(()=>document.querySelector('#backend-tag')?.textContent==='CPU WORKER');
  await page.selectOption('#resolution','256');await page.selectOption('#samples','8');await page.locator('#render-button').click();
  let complete=await until(async()=>{const s=await state(id);return s.run?.status==='complete'&&s;});
  assert.equal(complete.run.completed,64);report.solo=complete.history[0];
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  const phone=await mobile.newPage();watch(phone);await phone.goto(`${base}/join/${id}?cpu=1`);
  await phone.waitForFunction(()=>document.querySelector('#connection')?.textContent==='Live connection');
  await phone.fill('#device-name','Audience phone');await phone.locator('#contribute-button').click();
  await phone.waitForFunction(()=>document.querySelector('#backend-tag')?.textContent==='CPU WORKER');
  await until(async()=>(await state(id)).clients.filter(c=>c.enabled).length===2);
  await page.locator('#render-button').click();
  complete=await until(async()=>{const s=await state(id);return s.run?.id===2&&s.run.status==='complete'&&s;});
  assert.equal(complete.history[0].workers,2);report.multi=complete.history[0];
  await page.waitForFunction(()=>document.querySelector('#benchmark-title')?.textContent.includes('× solo'));
  await page.selectOption('#resolution','512');await page.selectOption('#samples','32');await page.locator('#render-button').click();
  complete=await until(async()=>{const s=await state(id);return s.run?.id===3&&s.run.status==='complete'&&s;});
  assert.equal(complete.run.completed,256);assert.equal(complete.history[0].workers,2);
  await page.locator('.toggle-label').click();
  assert.equal(await page.locator('#show-owners').isChecked(),true);
  await page.waitForFunction(()=>document.querySelector('#render-status')?.textContent==='COMPLETE');
  await page.screenshot({path:new URL('studio-complete.png',directory).pathname,fullPage:true});
  await phone.screenshot({path:new URL('phone-contributor.png',directory).pathname,fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const viewer=await browser.newPage();watch(viewer);await viewer.goto(`${base}/r/${id}`);
  await viewer.waitForFunction(()=>document.querySelector('#render-status')?.textContent==='COMPLETE');
  await until(async()=>(await viewer.locator('#render-canvas').evaluate(c=>c.toDataURL()))===(await page.locator('#render-canvas').evaluate(c=>c.toDataURL())));
  assert.equal(await viewer.locator('#render-button').isDisabled(),true);
  await viewer.close();report.replay='identical completed canvas';
  const download=page.waitForEvent('download');await page.locator('#download-button').click();
  await(await download).saveAs(new URL('render.png',directory).pathname);
  await page.locator('#share-button').click();assert.equal(await page.locator('#share-dialog').isVisible(),true);
  await page.locator('#share-dialog .dialog-close').click();
  await page.selectOption('#resolution','512');await page.selectOption('#samples','64');await page.locator('#render-button').click();
  await until(async()=>{const s=await state(id);return s.run?.id===4&&s.clients.some(c=>c.label==='Audience phone'&&c.busy);});
  await mobile.close();
  complete=await until(async()=>{const s=await state(id);return s.run?.id===4&&s.run.status==='complete'&&s;},120000);
  assert.ok(complete.run.retries>=1);assert.equal(complete.run.completed,256);report.reassignment=complete.run.retries;
  await page.locator('#contribute-button').click();
  // Exercise the normal GPU path independently of forced-CPU compatibility tests.
  const gpuContext=await browser.newContext({viewport:{width:1440,height:1080}}),gpuPage=await gpuContext.newPage();watch(gpuPage);
  await gpuPage.goto(base);await gpuPage.waitForFunction(()=>document.querySelector('#connection')?.textContent==='Live connection');
  await gpuPage.locator('#contribute-button').click();
  await gpuPage.waitForFunction(()=>['WEBGPU','CPU WORKER'].includes(document.querySelector('#backend-tag')?.textContent));
  report.gpuBackend=await gpuPage.locator('#backend-tag').textContent();
  const gpuRoom=(await gpuPage.locator('#room-code').textContent()).trim();await gpuPage.locator('[data-preset=solstice]').click();
  await gpuPage.selectOption('#resolution','512');await gpuPage.selectOption('#samples','32');await gpuPage.locator('#render-button').click();
  const gpuRun=await until(async()=>{const s=await state(gpuRoom);return s.run?.status==='complete'&&s;});
  report.gpuRun=gpuRun.history[0];
  report.gpuInfo=await gpuPage.evaluate(async()=>{const adapter=await navigator.gpu?.requestAdapter();return adapter?{vendor:adapter.info.vendor,architecture:adapter.info.architecture,device:adapter.info.device,description:adapter.info.description,isFallbackAdapter:adapter.info.isFallbackAdapter}:null;});
  assert.equal(await gpuPage.locator('#backend-tag').textContent(),report.gpuBackend,'GPU must not silently fall back during render');
  const variation=await gpuPage.locator('#render-canvas').evaluate(c=>new Set(c.getContext('2d').getImageData(0,0,c.width,c.height).data).size);
  assert.ok(variation>100,'GPU path produces a non-empty, varied image');
  await gpuPage.screenshot({path:new URL('studio-webgpu.png',directory).pathname,fullPage:true});
  const gpuDownload=gpuPage.waitForEvent('download');await gpuPage.locator('#download-button').click();await(await gpuDownload).saveAs(new URL('render-webgpu.png',directory).pathname);
  await gpuPage.setViewportSize({width:390,height:844});
  await gpuPage.screenshot({path:new URL('studio-mobile.png',directory).pathname,fullPage:true});
  assert.equal(await gpuPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  report.consoleErrors=errors;report.notices=notices;assert.deepEqual(errors,[]);
  await writeFile(new URL('browser-report.json',directory),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} finally {await browser.close();}
